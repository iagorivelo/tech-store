// Conjunto de ícones SVG reutilizáveis (stroke = currentColor, herdam a cor do
// texto). Server-safe: sem estado/hooks. Use em qualquer parte do projeto.

function Svg({ size = 24, strokeWidth = 2, children, ...props }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...props}
    >
      {children}
    </svg>
  );
}

